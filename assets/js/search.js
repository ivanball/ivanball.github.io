/* Global site search.

   The index (assets/data/search-index.json) is generated by tools/build-docs.mjs:
   one record per H2 section of every reference document, plus the hand-authored
   pages and the published article series. It is fetched ONCE, on first open, so a
   visitor who never searches pays nothing for this.

   No dependency and no service: the corpus is small enough to score in a loop,
   and a search box that phones a third party would be the only such request on
   the site.

   Markup comes from searchDialogHtml() in the generator and is present on every
   page. If this script never runs, the button simply does nothing, which is the
   right failure: nothing else on the page depends on it. */
(function () {
  "use strict";

  var INDEX_URL = "/assets/data/search-index.json";
  var MAX_RESULTS = 25;
  var MIN_QUERY = 2;

  var dialog, input, list, status;
  var records = null;          // loaded index, with a lowercase haystack per record
  var loading = false;
  var active = -1;             // highlighted result
  var lastQuery = "";

  /* ----- loading ----- */

  function load() {
    if (records || loading) { return Promise.resolve(); }
    loading = true;
    setStatus("Loading the index…");
    return fetch(INDEX_URL, { credentials: "omit" })
      .then(function (r) {
        if (!r.ok) { throw new Error("HTTP " + r.status); }
        return r.json();
      })
      .then(function (data) {
        records = (data && data.r ? data.r : []).map(function (rec) {
          /* One lowercase blob per record, built once. Everything the query can
             match lives here; the original fields stay for display. */
          rec._h = [rec.t, rec.d, rec.k, rec.x, rec.i].filter(Boolean).join(" ").toLowerCase();
          rec._t = (rec.t || rec.d || "").toLowerCase();
          return rec;
        });
        loading = false;
        setStatus("");
        if (input.value.trim()) { run(input.value); }
      })
      .catch(function (err) {
        loading = false;
        records = null;
        setStatus("Search is unavailable right now (" + err.message + ").");
      });
  }

  /* ----- scoring -----
     Deliberately simple: a hit in the section heading outranks a hit in the
     identifier list, which outranks a hit in the excerpt. Every term must appear
     somewhere, so a two-word query narrows instead of widening. */

  function terms(q) {
    return q.toLowerCase().split(/[^a-z0-9_.#+]+/i).filter(function (t) { return t.length > 1; });
  }

  function score(rec, ts, phrase) {
    var total = 0;
    for (var i = 0; i < ts.length; i++) {
      var t = ts[i];
      if (rec._h.indexOf(t) === -1) { return 0; }     // every term must be present
      if (rec._t.indexOf(t) !== -1) { total += 40; }
      if (rec.i && rec.i.toLowerCase().indexOf(t) !== -1) { total += 25; }
      if (rec.x && rec.x.toLowerCase().indexOf(t) !== -1) { total += 8; }
      /* Whole-word beats a substring: "outbox" should not lose to "outboxes". */
      if (new RegExp("\\b" + t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\\b").test(rec._h)) { total += 12; }
    }
    if (phrase.length >= MIN_QUERY) {
      if (rec._t.indexOf(phrase) !== -1) {
        total += 120;
        /* Specificity: "Outbox Pattern with Dual Dispatch" is a better answer for
           "outbox" than a 74-character section heading that merely contains the
           word. Short titles that match are more likely to be ABOUT the query. */
        if (rec._t.length <= 60) { total += 30; }
      } else if (rec._h.indexOf(phrase) !== -1) { total += 45; }
    }
    /* A document's own record is the better landing spot than one of its
       sections when both match comparably: the reader gets the whole record. */
    if (!rec.t) { total += 25; }
    return total;
  }

  function search(q) {
    var ts = terms(q);
    if (!ts.length) { return []; }
    var phrase = q.trim().toLowerCase();
    var hits = [];
    for (var i = 0; i < records.length; i++) {
      var s = score(records[i], ts, phrase);
      if (s > 0) { hits.push({ rec: records[i], s: s }); }
    }
    hits.sort(function (a, b) { return b.s - a.s; });
    return hits.slice(0, MAX_RESULTS);
  }

  /* ----- rendering ----- */

  function escapeHtml(s) {
    return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  }

  /* Mark the matched terms in already-escaped text. Done on the escaped string
     so a record can never inject markup. */
  function mark(text, ts) {
    var out = escapeHtml(text);
    for (var i = 0; i < ts.length; i++) {
      var safe = ts[i].replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      out = out.replace(new RegExp("(" + safe + ")(?![^<]*>)", "ig"), "<mark>$1</mark>");
    }
    return out;
  }

  function render(hits, q) {
    var ts = terms(q);
    list.innerHTML = hits.map(function (hit, i) {
      var r = hit.rec;
      var heading = r.t || r.d;
      var context = r.t ? r.d : r.k;
      var external = r.e ? ' target="_blank" rel="noopener"' : "";
      return '<li class="search-result"' + (i === 0 ? ' data-active="true"' : "") + '>' +
        '<a href="' + escapeHtml(r.u) + '"' + external + '>' +
          '<span class="search-kind">' + escapeHtml(r.k) + (r.e ? " ↗" : "") + '</span>' +
          '<span class="search-title">' + mark(heading, ts) + '</span>' +
          '<span class="search-context">' + escapeHtml(context) + '</span>' +
          (r.x ? '<span class="search-excerpt">' + mark(r.x, ts) + '</span>' : "") +
        '</a></li>';
    }).join("");
    active = hits.length ? 0 : -1;
  }

  function setStatus(text) { status.textContent = text; }

  function run(q) {
    lastQuery = q;
    if (!records) { load(); return; }
    var trimmed = q.trim();
    if (trimmed.length < MIN_QUERY) {
      list.innerHTML = "";
      active = -1;
      setStatus(trimmed ? "Keep typing…" : "");
      return;
    }
    var hits = search(trimmed);
    render(hits, trimmed);
    setStatus(hits.length
      ? hits.length + (hits.length === MAX_RESULTS ? "+ results" : " result" + (hits.length === 1 ? "" : "s"))
      : "No results for “" + trimmed + "”.");
  }

  /* ----- keyboard navigation ----- */

  function items() { return list.querySelectorAll(".search-result"); }

  function move(delta) {
    var all = items();
    if (!all.length) { return; }
    if (active >= 0 && all[active]) { all[active].removeAttribute("data-active"); }
    active = (active + delta + all.length) % all.length;
    all[active].setAttribute("data-active", "true");
    all[active].scrollIntoView({ block: "nearest" });
  }

  function openCurrent() {
    var all = items();
    if (active < 0 || !all[active]) { return; }
    var link = all[active].querySelector("a");
    if (link) { link.click(); }
  }

  /* ----- open / close ----- */

  function open(seed) {
    if (!dialog || dialog.open) { return; }
    dialog.showModal();
    input.value = seed || "";
    load();
    run(input.value);
    input.focus();
  }

  function close() {
    if (dialog && dialog.open) { dialog.close(); }
  }

  function init() {
    dialog = document.getElementById("site-search");
    if (!dialog || typeof dialog.showModal !== "function") { return; }
    input = dialog.querySelector(".search-input");
    list = dialog.querySelector(".search-results");
    status = dialog.querySelector(".search-status");

    document.querySelectorAll("[data-search-open]").forEach(function (btn) {
      btn.addEventListener("click", function () { open(""); });
    });
    dialog.querySelectorAll("[data-search-close]").forEach(function (btn) {
      btn.addEventListener("click", close);
    });

    /* Clicking the backdrop closes. The dialog fills its own box, so a click
       whose target IS the dialog element landed outside the panel. */
    dialog.addEventListener("click", function (e) {
      if (e.target === dialog) { close(); }
    });

    var debounce = null;
    input.addEventListener("input", function () {
      window.clearTimeout(debounce);
      debounce = window.setTimeout(function () { run(input.value); }, 90);
    });

    input.addEventListener("keydown", function (e) {
      if (e.key === "ArrowDown") { e.preventDefault(); move(1); }
      else if (e.key === "ArrowUp") { e.preventDefault(); move(-1); }
      else if (e.key === "Enter") { e.preventDefault(); openCurrent(); }
    });

    /* Ctrl/Cmd+K anywhere, and "/" when the visitor is not already typing. */
    document.addEventListener("keydown", function (e) {
      var typing = /^(INPUT|TEXTAREA|SELECT)$/.test(e.target.tagName) || e.target.isContentEditable;
      if ((e.key === "k" || e.key === "K") && (e.metaKey || e.ctrlKey)) {
        e.preventDefault();
        dialog.open ? close() : open("");
      } else if (e.key === "/" && !typing && !dialog.open) {
        e.preventDefault();
        open("");
      }
    });

    /* Re-running on reopen keeps the previous query's results in place. */
    dialog.addEventListener("close", function () { lastQuery = input.value; });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
